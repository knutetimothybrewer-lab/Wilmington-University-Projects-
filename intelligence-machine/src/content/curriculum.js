export function installCurriculum() {
  for (const c of chapterRegistry) {
    c.scenes = lectureCurriculum[c.id];
    c.status = "lecture";
    c.scenes.forEach((scene, i) => {
      scene.notes.demonstration =
        demonstrationDirections[scene.lab] ||
        "Invite participants to explain the concept in their own words, compare the analogy with its limitations, and propose a classroom application. Use Dive Deeper to examine the technical explanation before asking the critical question.";
      scene.notes.transition =
        i < c.scenes.length - 1
          ? "Carry the central idea into “" +
            c.scenes[i + 1].name +
            "”. Ask what new evidence or mechanism the next scene adds."
          : "Synthesize the chapter, address unresolved questions, then return to campus or advance to the next building.";
    });
    c.simulations = c.scenes
      .filter((s) => s.lab && s.lab !== "assessment")
      .map((s) => s.lab);
    c.assessments = chapterQuestions[c.id];
    c.qualification = c.scenes[0].deeper;
    c.instructorNotes.facilitation =
      "Use the suggested pacing flexibly. Predict → manipulate → explain → qualify. Every advance and answer reveal remains under instructor control.";
  }
}
